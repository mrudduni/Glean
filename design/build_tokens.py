#!/usr/bin/env python3
"""Single source for the Glean palette. Writes design/tokens.json and design/tokens.css.

Edit LIGHT / DARK below, then run:  python design/build_tokens.py
Then check:  python design/check_cvd.py  and  python content/validate.py tokens
"""
import json
from pathlib import Path

OUT = Path(__file__).parent

LIGHT = {
    "color": {"bg": "#F6F2E9", "surface": "#FFFFFF", "fg": "#1E2A22", "muted": "#55615A", "border": "#D8D1BF",
              "accent": "#1B5E8C", "good": "#1B6E3C", "fair": "#8A5A00", "limited": "#A3362B"},
    # Fills for calendar cells and map. Dark text (color-fg) sits on top, so each is light enough for 4.5:1.
    "crop": {"corn": "#FBB012", "sorghum": "#E97E5E", "wheat": "#E6CFA1", "soybean": "#B7E268",
             "alfalfa": "#28C073", "triticale": "#D29EF0", "rye_cover": "#68A1BA", "cotton": "#EEB1C4",
             "fallow": "#9E9384", "bare": "#F1EBDD"},
    # Chart lines on a white surface, 3:1 or better; found by a colour-blind-safe search (see check_cvd.py).
    # Still pair with dashes or direct labels.
    "rot": {"R0": "#4B4B4B", "R1": "#7E2507", "R2": "#5549EC", "R3": "#6E207A", "R4": "#B87DDA",
            "R5": "#DF5E1A", "R6": "#4DA271"},
    "risk": {"heat": "#EF6F18", "frost": "#4E9CCF", "dry": "#6C3F0A", "storm": "#791BC7", "wind": "#40595D"},
    "font": {"display": "'Fraunces', 'Georgia', serif",
             "body": "'Source Sans 3', system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
             "mono": "'IBM Plex Mono', ui-monospace, 'SF Mono', Menlo, Consolas, monospace"},
    "radius": "10px",
}

DARK = {
    "color": {"bg": "#121A15", "surface": "#1B251E", "fg": "#EEF2EA", "muted": "#AAB6AD", "border": "#33423A",
              "accent": "#7FC0EE", "good": "#6FCB8D", "fair": "#E3B14A", "limited": "#F08A7C"},
    "crop": {"corn": "#714F08", "sorghum": "#69392A", "wheat": "#685D48", "soybean": "#52662F", "alfalfa": "#125634", "triticale": "#5E476C", "rye_cover": "#2F4854", "cotton": "#6B5058", "fallow": "#4A453D", "bare": "#2B2823"},
    "rot": {"R0": "#BDBDBD", "R1": "#64F1FB", "R2": "#417482", "R3": "#F1C090", "R4": "#BF2ADE",
            "R5": "#C53D0C", "R6": "#BDEE22"},
    "risk": {"heat": "#B45631", "frost": "#2876FE", "dry": "#BFB826", "storm": "#9257AF", "wind": "#606F6E"},
}


def css_block(sel, d, fonts=True):
    lines = [f"{sel} {{"]
    for grp in ("color", "crop", "rot", "risk"):
        for k, v in d[grp].items():
            lines.append(f"  --{grp}-{k}: {v};")
    if fonts:
        for k, v in LIGHT["font"].items():
            lines.append(f"  --font-{k}: {v};")
        lines.append(f"  --radius: {LIGHT['radius']};")
    lines.append("}")
    return "\n".join(lines)


def main():
    tj = {**LIGHT, "dark": DARK}
    # Text colour for crop cells. Every fill is built to take this colour at 4.5:1 or better.
    tj["crop_text"] = {k: LIGHT["color"]["fg"] for k in LIGHT["crop"]}
    tj["dark"] = {**DARK, "crop_text": {k: DARK["color"]["fg"] for k in DARK["crop"]}}
    (OUT / "tokens.json").write_text(json.dumps(tj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    css = (
        "/* Glean design tokens. Generated by design/build_tokens.py, do not edit by hand.\n"
        "   Fonts: load Fraunces, Source Sans 3 and IBM Plex Mono from Google Fonts; system fonts are the fallback.\n"
        "   Body text 16px or larger. Use font-variant-numeric: tabular-nums on numbers.\n"
        "   Crop fills are light on purpose: put --color-fg text on top. Rotation lines are for strokes on --color-surface.\n"
        "   Pair --color-good/fair/limited with a word, never colour alone. */\n"
        + css_block(":root", LIGHT) + "\n\n"
        "@media (prefers-color-scheme: dark) {\n"
        + css_block("  :root:not([data-theme=\"light\"])", DARK, fonts=False).replace("\n", "\n  ").replace("\n  }", "\n  }")
        + "\n}\n\n"
        + css_block("[data-theme=\"dark\"]", DARK, fonts=False) + "\n"
    )
    (OUT / "tokens.css").write_text(css, encoding="utf-8")
    print("wrote tokens.json and tokens.css")


if __name__ == "__main__":
    main()
